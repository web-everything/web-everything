import { accessSync, constants, lstatSync, readFileSync, readdirSync, realpathSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { tmpdir, userInfo } from 'node:os';
import { dirname, isAbsolute, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { types } from 'node:util';
import { resolveOrgAwareShimDir, shimGhPath } from './gh-app-shim.mjs';
import { GITHUB_APP_ROLES } from './github-app-identity.mjs';
import { WORKER_MARKER_ENV, WORKER_MARKER_VALUE } from '../operations/session-role.mjs';

/** Launcher-owned env keys that the agent's own shells must also receive (codex policy.set, claude --settings env). */
export const LAUNCHER_POLICY_KEYS = Object.freeze(['PATH', 'HOME', 'SHELL', 'TMPDIR', 'WE_GH_DAEMON_CALLER',
  'WE_GH_AUTH_PERSONAL_FALLBACK', 'WE_GITHUB_APP_ROLE', WORKER_MARKER_ENV]);

const HERE = dirname(fileURLToPath(import.meta.url));
const FIXED_PATH = ['/usr/bin', '/bin', '/usr/sbin', '/sbin', '/usr/local/bin', '/opt/homebrew/bin'];
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const COMMON = ['agent', 'githubRole', 'cwd', 'processGroup', 'tempRoot', 'env'];
const CODEX = ['sandbox', 'outputSchemaFile', 'outputLastMessageFile', 'ephemeral', 'addDirs', 'model', 'config', 'resumeThreadId'];
const CLAUDE = ['print', 'sessionId', 'resumeId', 'model', 'outputFormat', 'verbose', 'prompt'];
const IO_KEYS = ['admit', 'spawn', 'resolveBinary', 'ghShimDir', 'codexShimDir', 'manifest', 'shellsFile', 'execPath', 'user'];
const GH_HEADER = '// AUTO-GENERATED by we:scripts/lib/gh-app-shim.mjs';
const fail = reason => { throw new TypeError(`agent-launch: ${reason}`); };

// Inspect descriptors, never values through property access, until all data is ours.
function snapshot(input) {
  const active = new WeakSet(), copies = new WeakMap();
  let nodes = 0;
  function copy(value, depth = 0) {
    if (++nodes > 10000 || depth > 64) fail('snapshot limit exceeded; simplify the descriptor and retry');
    if (typeof value === 'function' || typeof value === 'symbol') fail('function/symbol value');
    if (value === null || typeof value !== 'object') return value;
    if (types.isProxy(value)) fail('Proxy value');
    if (active.has(value)) fail('cyclic value');
    if (copies.has(value)) return copies.get(value);
    const array = Array.isArray(value), proto = Object.getPrototypeOf(value);
    if (array ? proto !== Array.prototype : proto !== Object.prototype && proto !== null) fail('non-plain prototype');
    const props = Object.getOwnPropertyDescriptors(value), keys = Reflect.ownKeys(props);
    if (keys.some(key => typeof key === 'symbol')) fail('symbol key');
    for (const key of keys) if (!Object.hasOwn(props[key], 'value')) fail(`accessor property ${key}`);
    if (array && (keys.length - 1 !== props.length.value
      || keys.some(key => key !== 'length' && !/^(0|[1-9][0-9]*)$/.test(key)))) fail('sparse or decorated array');
    const out = array ? [] : Object.create(null);
    active.add(value); copies.set(value, out);
    for (const key of keys) if (!array || key !== 'length') out[key] = copy(props[key].value, depth + 1);
    active.delete(value);
    return out;
  }
  return copy(input);
}
function record(value, name) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) fail(`${name} must be a record`);
}
function text(value, name) {
  if (typeof value !== 'string' || !value || value.startsWith('-') || value.includes('\0')) fail(`${name} must be a non-option, NUL-free string`);
  return value;
}
function absolute(value, name) {
  if (!isAbsolute(text(value, name))) fail(`${name} must be absolute`);
  return value;
}
function choice(value, choices, name) {
  if (!choices.includes(value)) fail(`${name} must be ${choices.join('|')}`);
  return value;
}
function flag(value, name) {
  if (value !== undefined && typeof value !== 'boolean') fail(`${name} must be boolean`);
  return value === true;
}
function id(value, name) {
  if (!UUID.test(text(value, name)) || value.length !== 36) fail(`${name} must be a UUID`);
  return value;
}
function paths(value, name) {
  if (!Array.isArray(value)) fail(`${name} must be an array`);
  return value.map(p => absolute(p, name));
}

// D5: caller-allowlisted keys. Launcher-owned keys (PATH, HOME, USER, LOGNAME, SHELL, CODEX_HOME, TMP*, WE_GH_*) are never read from the caller.
const CALLER_KEYS = new Set(['TERM', 'LANG', 'TZ', 'NO_COLOR', 'FORCE_COLOR', 'CI',
  'HTTP_PROXY', 'HTTPS_PROXY', 'NO_PROXY', 'http_proxy', 'https_proxy', 'no_proxy']);
const AGENT_KEYS = { codex: ['OPENAI_API_KEY', 'CODEX_API_KEY'], claude: ['ANTHROPIC_API_KEY', 'CLAUDE_CODE_OAUTH_TOKEN'] };
// Validate all serialization before dropping anything outside the closed allowlist.
function envRecord(value) {
  record(value, 'env');
  for (const [key, entry] of Object.entries(value)) {
    if (!key || key.includes('=') || key.includes('\0')) fail(`env key ${JSON.stringify(key)} must be non-empty and contain neither '=' nor NUL`);
    if (entry !== undefined && (typeof entry !== 'string' || entry.includes('\0'))) fail(`env.${key} must be a NUL-free string or undefined`);
  }
  return value;
}
function callerEnv(env, agent) {
  const keep = new Set([...CALLER_KEYS, ...AGENT_KEYS[agent]]);
  return Object.fromEntries(Object.entries(env).filter(([key, entry]) => entry !== undefined && (keep.has(key) || key.startsWith('LC_'))));
}
function configValue(key, value) {
  switch (key) {
    case 'model_reasoning_effort': return choice(value, ['low', 'medium', 'high', 'xhigh', 'max', 'ultra'], key);
    case 'sandbox_workspace_write.network_access':
      if (typeof value !== 'boolean') fail(`${key} must be boolean`);
      return String(value);
    case 'sandbox_workspace_write.writable_roots': return JSON.stringify(paths(value, key));
    default: fail(`unknown config key ${key}`);
  }
}
// `launcher` carries launcher-owned argv: codex `-c` pairs, or the claude --settings JSON string.
function argsFrom(d, launcher) {
  record(d, 'descriptor');
  choice(d.agent, ['claude', 'codex'], 'agent');
  for (const key of Object.keys(d)) if (![...COMMON, ...(d.agent === 'codex' ? CODEX : CLAUDE)].includes(key)) fail(`unknown field ${key}`);
  choice(d.githubRole, GITHUB_APP_ROLES, 'githubRole');
  absolute(d.cwd, 'cwd'); flag(d.processGroup, 'processGroup');
  if (d.tempRoot !== undefined) absolute(d.tempRoot, 'tempRoot');
  if (d.env !== undefined) envRecord(d.env);
  if (d.model !== undefined && (!/^[a-z0-9][a-z0-9._:/-]*$/i.test(text(d.model, 'model')) || /\s/.test(d.model))) fail('model must be a model name');
  const args = [];
  const option = (key, token, check = text) => { if (d[key] !== undefined) args.push(token, check(d[key], key)); };
  if (d.agent === 'claude') {
    if (d.sessionId !== undefined && d.resumeId !== undefined) fail('sessionId and resumeId are mutually exclusive');
    if (flag(d.print, 'print')) args.push('-p');
    option('sessionId', '--session-id', id); option('resumeId', '--resume', id); option('model', '--model');
    option('outputFormat', '--output-format', (v, k) => choice(v, ['text', 'json', 'stream-json'], k));
    if (flag(d.verbose, 'verbose')) args.push('--verbose');
    if (launcher) args.push('--settings', launcher);
    if (d.prompt !== undefined) args.push('--', text(d.prompt, 'prompt'));
    return args;
  }
  args.push('exec', '--json', '-s', choice(d.sandbox, ['read-only', 'workspace-write'], 'sandbox'), '--skip-git-repo-check', '-C', d.cwd);
  option('outputSchemaFile', '--output-schema', absolute); option('outputLastMessageFile', '-o', absolute);
  if (flag(d.ephemeral, 'ephemeral')) args.push('--ephemeral');
  if (d.addDirs !== undefined) for (const dir of paths(d.addDirs, 'addDirs')) args.push('--add-dir', dir);
  option('model', '-m');
  if (d.config !== undefined) {
    record(d.config, 'config');
    for (const [key, value] of Object.entries(d.config)) args.push('-c', `${key}=${configValue(key, value)}`);
  }
  for (const [key, value] of Object.entries(launcher ?? {})) args.push('-c', `${key}=${JSON.stringify(value)}`);
  if (d.resumeThreadId !== undefined) {
    const thread = id(d.resumeThreadId, 'resumeThreadId');
    if (d.ephemeral) fail('resumeThreadId conflicts with ephemeral');
    if (d.outputSchemaFile !== undefined) fail('resumeThreadId conflicts with outputSchemaFile');
    args.push('resume', thread, '-');
  }
  return args;
}

function installDirs(home) {
  return [...FIXED_PATH, join(home, '.local/bin'), join(home, '.npm-global/bin'), join(home, '.volta/bin')];
}
// Fixed installation lookup, independently checked against the final child PATH.
function resolveBinary(agent) { return findAgentBinary(agent, installDirs(userInfo().homedir)); }

/** Lookup over explicit directories for hermetic fixtures; production supplies only its fixed list. */
export function findAgentBinary(agent, dirs) {
  for (const dir of dirs) {
    try {
      const file = join(dir, agent);
      if (!isAbsolute(file) || !statSync(file).isFile()) continue;
      accessSync(file, constants.X_OK);
      return file;
    } catch (error) {
      if (!['ENOENT', 'ENOTDIR'].includes(error.code)) fail(`${agent} binary unreadable; restore installation access and retry`);
    }
  }
  fail(`${agent} binary not found; install it in a well-known installation directory`);
}

/** Pure argv projection (no launcher-owned argv), retained for direct-task's existing argv consumers. */
export function buildAgentArgs(descriptor) { return argsFrom(snapshot(descriptor)); }

// First executable `name` on an all-absolute PATH.
function firstOnPath(name, path) {
  const dirs = path.split(':');
  for (const dir of dirs) if (!isAbsolute(dir)) fail('relative or empty child PATH entry; use absolute directories and retry');
  for (const dir of dirs) {
    try {
      const file = `${dir}/${name}`;
      if (!statSync(file).isFile()) continue;
      accessSync(file, constants.X_OK);
      return file;
    } catch (error) {
      if (!['ENOENT', 'ENOTDIR'].includes(error.code)) fail('child PATH binary unreadable; restore access and retry');
    }
  }
  fail(`${name} not found on child PATH; restore the guard and retry`);
}

// D1/D2: a trusted, owner-only regular file (not a symlink); returns its bytes.
function trustedFile(file, what) {
  let st;
  try { st = lstatSync(file); } catch { fail(`${what} missing; restore it and retry`); }
  if (!st.isFile() || st.isSymbolicLink()) fail(`${what} must be a regular file, not a symlink`);
  if (st.uid !== process.getuid()) fail(`${what} must be owned by the launching user`);
  if ((st.mode & 0o022) !== 0) fail(`${what} must not be group- or world-writable`);
  return readFileSync(file);
}
function trustedDir(dir, what) {
  let st;
  try { st = lstatSync(dir); } catch { fail(`${what} directory missing; restore it and retry`); }
  if (!st.isDirectory() || st.isSymbolicLink()) fail(`${what} directory must be a real directory`);
  if (st.uid !== process.getuid() || (st.mode & 0o022) !== 0) fail(`${what} directory must be owner-only writable`);
}
const sha = bytes => createHash('sha256').update(bytes).digest('hex');

// Returns { dirs: [guard dirs in PATH order], guards: [{name, path, sha256}] }, or refuses.
const HEX64 = /^[0-9a-f]{64}$/;
const CODEX_PINNED = ['npm', 'npx', 'playwright', 'vitest'];
// The manifest is itself a guard input: demand the exact name sets so an emptied or trimmed one cannot disable a guard.
function validManifest(manifest, agent) {
  const same = (obj, names) => obj && typeof obj === 'object' && !Array.isArray(obj)
    && JSON.stringify(Object.keys(obj).sort()) === JSON.stringify(names)
    && Object.values(obj).every(h => typeof h === 'string' && HEX64.test(h));
  const entry = manifest?.[agent];
  const codex = agent === 'codex';
  if (!entry || !same(entry.pinned, codex ? CODEX_PINNED : []) || !same(entry.sourced, codex ? ['_guard.sh'] : [])
    || JSON.stringify(entry.generated) !== '["gh"]') fail(`guard manifest for ${agent} is invalid; restore agent-launch-guards.json and retry`);
  return entry;
}
// A guard directory may hold only its manifest names (plus the gh shim's atomic-rename temp file).
function onlyNames(dir, names, what, tempPattern) {
  for (const name of readdirSync(dir)) {
    if (!names.includes(name) && !(tempPattern && tempPattern.test(name))) fail(`${what} directory has an unexpected file ${name}; remove it and retry`);
  }
}
function guardSet(agent, io) {
  const manifest = io.manifest ?? JSON.parse(trustedFile(join(HERE, 'agent-launch-guards.json'), 'guard manifest').toString('utf8'));
  const entry = validManifest(manifest, agent);
  const dirs = [], guards = [];
  if (Object.keys(entry.pinned).length) {
    const dir = io.codexShimDir ?? join(HERE, '..', 'codex-shims');
    trustedDir(dir, `${agent} guard shim`);
    onlyNames(dir, [...Object.keys(entry.pinned), ...Object.keys(entry.sourced)], `${agent} guard shim`);
    for (const [name, want] of [...Object.entries(entry.pinned), ...Object.entries(entry.sourced)]) {
      const path = join(dir, name), got = sha(trustedFile(path, `guard shim ${name}`));
      if (got !== want) fail(`guard shim ${name} differs from agent-launch-guards.json; review the change and update the manifest`);
      guards.push({ name, path, sha256: got });
    }
    dirs.push(dir);
  }
  for (const name of entry.generated) {
    if (name !== 'gh') fail(`unknown generated guard ${name}`);
    const dir = io.ghShimDir ?? resolveOrgAwareShimDir();
    if (!dir) fail('org-aware gh shim not found; regenerate it by dispatching through the daemon and retry');
    absolute(dir, 'gh shim dir'); trustedDir(dir, 'gh shim');
    onlyNames(dir, ['gh'], 'gh shim', /^gh\.tmp-\d+-\d+$/);
    const path = shimGhPath(dir), bytes = trustedFile(path, 'gh shim'), body = bytes.toString('utf8');
    const lines = body.split('\n');
    if (!lines[0].startsWith('#!') || !lines[1]?.startsWith(GH_HEADER)) fail('gh shim has the wrong header; regenerate it and retry');
    if (!body.includes('OWNER_INSTALLATIONS') || !body.includes('PERSONAL_FALLBACK_POLICY')) fail('gh shim is not org-aware; regenerate it and retry');
    guards.push({ name, path, sha256: sha(bytes) });
    dirs.push(dir);
  }
  return { dirs, guards };
}

function accountShell(user, io) {
  const shell = user.shell;
  if (typeof shell !== 'string' || !isAbsolute(shell)) fail('account shell must be an absolute path');
  let listed;
  try { listed = readFileSync(io.shellsFile ?? '/etc/shells', 'utf8').split('\n').map(l => l.trim()); } catch { fail('cannot read /etc/shells'); }
  if (!listed.includes(shell)) fail('account shell is not listed in /etc/shells');
  return shell;
}

/** Snapshot is the first operation, including before any test seam executes. */
export function buildAgentInvocation(descriptor, io = {}) {
  const d = snapshot(descriptor);
  for (const key of Object.keys(io)) if (!IO_KEYS.includes(key)) fail(`unknown io seam ${key}`);
  // Validate the entire snapshot before any IO seam executes.
  argsFrom(d);
  const caller = envRecord(d.env ?? {});
  const user = io.user ?? userInfo();
  const home = absolute(user.homedir, 'OS account HOME');
  const { dirs: guardDirs, guards } = guardSet(d.agent, io);
  // D3: launcher-owned PATH; caller entries only as a deduplicated absolute tail.
  const head = [...guardDirs, dirname(realpathSync.native(io.execPath ?? process.execPath)), ...installDirs(home)];
  const tail = caller.PATH === undefined ? [] : caller.PATH.split(':');
  for (const dir of tail) if (!isAbsolute(dir)) fail('relative or empty caller PATH entry; use absolute directories and retry');
  const path = [...new Set([...head, ...tail])].join(':');
  const tempRoot = d.tempRoot ?? tmpdir();
  const env = {
    ...callerEnv(caller, d.agent),
    PATH: path, HOME: home, USER: user.username, LOGNAME: user.username, SHELL: accountShell(user, io),
    TMPDIR: tempRoot, TMP: tempRoot, TEMP: tempRoot,
    WE_GH_DAEMON_CALLER: 'agent-launch', WE_GH_AUTH_PERSONAL_FALLBACK: 'refuse', WE_GITHUB_APP_ROLE: d.githubRole,
    [WORKER_MARKER_ENV]: WORKER_MARKER_VALUE,
  };
  // One list: the same launcher-owned keys are pinned for the agent's own shells (codex policy, claude --settings).
  const pinned = Object.fromEntries(LAUNCHER_POLICY_KEYS.map(key => [key, env[key]]));
  let launcher;
  if (d.agent === 'codex') {
    env.CODEX_HOME = join(home, '.codex');
    launcher = Object.fromEntries(Object.entries(pinned).map(([key, value]) => [`shell_environment_policy.set.${key}`, value]));
    if (d.tempRoot !== undefined) for (const key of ['TMP', 'TEMP']) launcher[`shell_environment_policy.set.${key}`] = tempRoot;
  } else {
    launcher = JSON.stringify({ env: pinned });
  }
  const args = argsFrom(d, launcher);
  try { if (!statSync(d.cwd).isDirectory()) fail('cwd must be an existing directory'); }
  catch { fail('cwd must be an existing directory'); }
  const file = absolute((io.resolveBinary ?? resolveBinary)(d.agent), 'resolved binary');
  // Invariant: every guarded name and the agent binary resolve first, on the final PATH, to the pinned file.
  // Native resolution preserves the lookup semantics used by stat/access and exec.
  for (const guard of guards) {
    if (realpathSync.native(firstOnPath(guard.name, path)) !== realpathSync.native(guard.path)) {
      fail(`${guard.name} on child PATH is not the pinned guard; remove the shadowing directory and retry`);
    }
  }
  if (realpathSync.native(firstOnPath(d.agent, path)) !== realpathSync.native(file)) {
    fail(`${d.agent} binary identity differs from child PATH; align PATH with the fixed installation and retry`);
  }
  return { file, args, guards, codexHome: env.CODEX_HOME, options: { shell: false, cwd: d.cwd, env, stdio: ['pipe', 'pipe', 'pipe'], detached: d.processGroup === true } };
}

// Admission hook point (SEC1 S3/S4 moves runtime admission here, #7090). It sees a frozen
// copy of the final spec (including guards) and can only refuse (return false or throw); it cannot rewrite it.
const frozen = value => Object.freeze(Array.isArray(value) ? value.map(frozen)
  : value && typeof value === 'object' ? Object.fromEntries(Object.entries(value).map(([k, v]) => [k, frozen(v)])) : value);

export function launchAgent(descriptor, io = {}) {
  const spec = buildAgentInvocation(descriptor, io);
  let admitted;
  if (typeof io.admit !== 'function') fail('launch not admitted');
  try { admitted = io.admit(frozen(spec)); }
  catch (e) { fail(`launch not admitted: ${e?.message ?? e}`); }
  if (admitted !== true) fail('launch not admitted');
  return (io.spawn ?? spawn)(spec.file, spec.args, spec.options);
}
