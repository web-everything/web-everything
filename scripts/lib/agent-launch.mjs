/**
 * Closed-grammar agent launcher (RS-7170-1 v2): the caller never chooses anything a guard depends on.
 * The launcher derives every guard input from fixed locations (its own module path, process.execPath,
 * os.userInfo(), the daemon's resolver for the generated gh shim), pins the guard files (we:scripts/lib/agent-launch-guards.json),
 * builds the child PATH itself and proves each guarded name resolves first to its pinned file.
 * Daemon-side git hardening (laneGitHardeningEnv, argv rewrites, filter-driver refusal) stays with daemon callers; agents keep the lane's own .githooks.
 * Child env: launcher-owned keys, a closed caller allowlist, per-agent credentials; everything else is dropped.
 * io seams (admit, spawn, resolveBinary, ghShimDir, codexShimDir, manifest, shellsFile, execPath, user) are trusted test seams; any other io key is refused.
 */
